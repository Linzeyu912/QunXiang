export const CHARACTER_BATCH_PROMPT = (bookTitle: string, batchNum: number, totalBatches: number): string =>
  `从书籍《${bookTitle}》中提取所有【人物角色】、【物品道具】、【地点场景】和【世界观与体系设定】。这是第 ${batchNum} 批（共 ${totalBatches} 批）。按系统提示给出的 JSON 对象结构返回。`;
